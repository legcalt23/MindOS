package com.example.neuv3.features.wallet.data

import com.example.neuv3.features.wallet.domain.model.SandboxPurchasePending
import com.example.neuv3.features.wallet.domain.model.WalletBalance
import com.example.neuv3.features.wallet.domain.model.WalletError
import com.example.neuv3.features.wallet.domain.model.WalletTransaction
import com.example.neuv3.features.wallet.domain.model.WalletVerifyResult
import dev.gitlive.firebase.Firebase
import dev.gitlive.firebase.functions.functions

/**
 * WalletApiClient.kt
 * Interface and Firebase implementation for calling wallet Cloud Functions.
 *
 * gitlive firebase-functions 2.4.0 API:
 *   - Firebase.functions.httpsCallable(name) → HttpsCallableReference
 *   - HttpsCallableReference.invoke()         → HttpsCallableResult  (no-arg)
 *   - HttpsCallableReference.invoke(data)     → HttpsCallableResult  (with data)
 *   - HttpsCallableResult.data<T>()           → T                    (generic method)
 *
 * Security contract:
 *  - Client never sends balance, newBalance, or final price to the server.
 *  - idempotencyKey is caller-supplied (one UUID per intent; reuse for retries).
 *  - sandboxToken in SandboxPurchasePending is never stored or logged by the client.
 *  - All amounts in responses come from the server and are treated as authoritative.
 */
interface WalletApiClient {

    /**
     * Fetches the current wallet balance from the server.
     * Call this after any mutation to display the up-to-date balance.
     * Never compute balance locally.
     */
    suspend fun getBalance(): WalletBalance

    /**
     * Fetches recent ledger transactions (newest first).
     * @param limit Maximum number of transactions to return (default 20).
     */
    suspend fun getTransactions(limit: Int = 20): List<WalletTransaction>

    /**
     * Begins a sandbox purchase for the given pack.
     * The server validates [packId] against its catalog — client never determines
     * coin amounts or prices.
     *
     * @param packId         One of: "coins_1", "coins_10", "coins_100"
     * @param idempotencyKey Unique UUID generated by the caller for this purchase intent.
     *                       Reuse the same key for retries of the same intent.
     */
    suspend fun initiatePurchase(packId: String, idempotencyKey: String): SandboxPurchasePending

    /**
     * Verifies and credits a sandbox purchase.
     * After this returns successfully, call [getBalance] to refresh the balance —
     * never apply the coin delta optimistically on the client.
     *
     * @param sandboxPurchaseId The purchaseId from [SandboxPurchasePending].
     * @param sandboxToken      The single-use token from [SandboxPurchasePending].
     * @param idempotencyKey    Unique UUID for this verify intent.
     */
    suspend fun verifyPurchase(
        sandboxPurchaseId: String,
        sandboxToken: String,
        idempotencyKey: String,
    ): WalletVerifyResult
}

// ── Firebase implementation ───────────────────────────────────────────────────

/**
 * Calls Firebase HTTPS callable Cloud Functions via dev.gitlive firebase-functions 2.4.0.
 * All exceptions are mapped to [WalletError] subtypes for safe handling upstream.
 */
class FirebaseWalletApiClient : WalletApiClient {

    private val fns get() = Firebase.functions

    override suspend fun getBalance(): WalletBalance = callSafely {
        val result = fns.httpsCallable("getWalletBalance").invoke()
        val data   = result.data<Any?>().requireMap("getWalletBalance response")
        val bal    = data["balance"].requireMap("balance field")
        parseBalance(bal)
    }

    override suspend fun getTransactions(limit: Int): List<WalletTransaction> = callSafely {
        val result = fns.httpsCallable("getWalletTransactions")
            .invoke(mapOf("limit" to limit))
        val data         = result.data<Any?>().requireMap("getWalletTransactions response")
        val transactions = data["transactions"] as? List<*> ?: emptyList<Any>()
        transactions.mapNotNull { item ->
            (item as? Map<*, *>)?.let(::parseTransaction)
        }
    }

    override suspend fun initiatePurchase(
        packId: String,
        idempotencyKey: String,
    ): SandboxPurchasePending = callSafely {
        val result = fns.httpsCallable("initiatePurchase")
            .invoke(mapOf("packId" to packId, "idempotencyKey" to idempotencyKey))
        val data = result.data<Any?>().requireMap("initiatePurchase response")
        SandboxPurchasePending(
            purchaseId    = data.str("purchaseId"),
            sandboxToken  = data.str("sandboxToken"),
            packId        = data.str("packId"),
            coinsAmount   = data.int("coinsAmount"),
            correlationId = data.str("correlationId"),
        )
    }

    override suspend fun verifyPurchase(
        sandboxPurchaseId: String,
        sandboxToken: String,
        idempotencyKey: String,
    ): WalletVerifyResult = callSafely {
        val result = fns.httpsCallable("verifyPurchase")
            .invoke(
                mapOf(
                    "sandboxPurchaseId" to sandboxPurchaseId,
                    "sandboxToken"      to sandboxToken,
                    "idempotencyKey"    to idempotencyKey,
                )
            )
        val data = result.data<Any?>().requireMap("verifyPurchase response")
        WalletVerifyResult(
            transactionId = data.str("transactionId"),
            coinsReceived = data.int("coinsReceived"),
            purchaseId    = data.str("purchaseId"),
            correlationId = data.str("correlationId"),
        )
    }
}

// ── Error mapping ─────────────────────────────────────────────────────────────

/**
 * Maps a Firebase Functions error code and message to a typed [WalletError].
 * Extracted as a pure function so it can be unit-tested without Firebase.
 *
 * Error codes use Firebase's gRPC naming (UPPER_SNAKE_CASE) as returned by the
 * gitlive SDK's FunctionsExceptionCode enum.
 */
internal fun mapErrorCode(code: String, message: String): WalletError = when (code) {
    "UNAUTHENTICATED"    -> WalletError.NotAuthenticated
    "PERMISSION_DENIED"  -> WalletError.NotAuthenticated
    "FAILED_PRECONDITION" -> when {
        "INSUFFICIENT_BALANCE"     in message -> WalletError.InsufficientBalance
        "WALLET_SUSPENDED"         in message -> WalletError.WalletSuspended
        "WALLET_FROZEN"            in message -> WalletError.WalletSuspended
        "PURCHASE_ALREADY_CREDITED" in message -> WalletError.PurchaseAlreadyCredited
        else -> WalletError.ServerError(message.ifBlank { "Request failed." })
    }
    "NOT_FOUND"          -> WalletError.PurchaseNotFound
    "RESOURCE_EXHAUSTED" -> WalletError.RateLimited
    else                 -> WalletError.ServerError(message.ifBlank { "Server error." })
}

// ── Private helpers ───────────────────────────────────────────────────────────

/**
 * Wraps a Firebase callable in consistent error handling.
 * Inspects the exception chain for Firebase Functions errors by class name
 * (avoids platform-specific exception imports in commonMain).
 */
private suspend fun <T> callSafely(block: suspend () -> T): T {
    return try {
        block()
    } catch (e: WalletError) {
        throw e                             // already mapped; re-throw
    } catch (e: Exception) {
        throw mapException(e)
    }
}

/**
 * Maps an arbitrary exception to a [WalletError] by inspecting the exception
 * chain for Firebase Functions errors. Avoids platform-specific imports by
 * using class name inspection.
 */
private fun mapException(e: Exception): WalletError {
    var current: Throwable? = e
    while (current != null) {
        val name = current::class.simpleName ?: ""
        if (name.contains("FunctionsException")) {
            // Extract the error code enum name via the message prefix or class-level inspection.
            // The gitlive SDK encodes the gRPC status code into the exception; we search the
            // full message string for known code tokens as a portable, reflect-free fallback.
            val fullMessage = buildString {
                append(current.message ?: "")
                // For Android/JVM, the exception detail may include the code name
            }
            return detectFromMessage(fullMessage)
        }
        current = current.cause
    }
    // No Firebase Functions exception detected; treat as network/unknown error
    return WalletError.NetworkError(rootCause = e)
}

/** Matches the first known error code found anywhere in [msg]. */
private fun detectFromMessage(msg: String): WalletError = when {
    "UNAUTHENTICATED"          in msg -> WalletError.NotAuthenticated
    "PERMISSION_DENIED"        in msg -> WalletError.NotAuthenticated
    "INSUFFICIENT_BALANCE"     in msg -> WalletError.InsufficientBalance
    "WALLET_SUSPENDED"         in msg || "WALLET_FROZEN" in msg -> WalletError.WalletSuspended
    "PURCHASE_ALREADY_CREDITED" in msg -> WalletError.PurchaseAlreadyCredited
    "PURCHASE_NOT_FOUND"       in msg -> WalletError.PurchaseNotFound
    "RATE_LIMIT"               in msg || "RESOURCE_EXHAUSTED" in msg -> WalletError.RateLimited
    else                               -> WalletError.ServerError(msg.ifBlank { "Server error." })
}

private fun parseBalance(map: Map<*, *>): WalletBalance = WalletBalance(
    availableBalance   = map.int("availableBalance"),
    purchasedBalance   = map.int("purchasedBalance"),
    promotionalBalance = map.int("promotionalBalance"),
    earnedBalance      = map.int("earnedBalance"),
)

private fun parseTransaction(map: Map<*, *>): WalletTransaction {
    // Sum all entry amounts for the net total (positive = credit, negative = debit).
    val entries = map["entries"] as? List<*> ?: emptyList<Any>()
    val total   = entries.sumOf { (it as? Map<*, *>)?.int("amount") ?: 0 }
    return WalletTransaction(
        transactionId = map.str("transactionId"),
        type          = map.str("type"),
        totalAmount   = total,
        createdAt     = map.long("createdAt"),
    )
}

// Safe accessors — return sensible defaults rather than throwing on missing keys.

private fun Any?.requireMap(context: String): Map<*, *> =
    this as? Map<*, *> ?: throw WalletError.Unknown(detail = "Unexpected server response: $context")

private fun Map<*, *>.str(key: String): String = this[key] as? String ?: ""
private fun Map<*, *>.int(key: String): Int    = (this[key] as? Number)?.toInt() ?: 0
private fun Map<*, *>.long(key: String): Long  = (this[key] as? Number)?.toLong() ?: 0L
